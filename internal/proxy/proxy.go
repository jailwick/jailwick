// Package proxy builds each sandbox's egress allowlist and reads the proxy's denied requests.
package proxy

import (
	"bufio"
	"fmt"
	"io"
	"net/url"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"
	"unicode"

	"github.com/jailwick/jailwick/internal/presets"
)

// Normalize turns user input (URL, host:port, domain) into an allowlist entry. A leading dot
// means the domain and all its subdomains.
func Normalize(in string) (string, error) {
	s := strings.ToLower(strings.TrimSpace(in))
	if strings.Contains(s, "://") {
		if u, err := url.Parse(s); err == nil {
			s = u.Host
		}
	}
	s, _, _ = strings.Cut(s, "/")
	if h, _, ok := strings.Cut(s, ":"); ok {
		s = h
	}
	if strings.HasPrefix(s, "*.") {
		s = s[1:]
	}
	if !presets.ValidHost(s) {
		return "", fmt.Errorf("%q is not a domain name", in)
	}
	return s, nil
}

// ParseList reads allowlist entries typed by the user: separated by commas, spaces or new lines,
// each a domain, a URL or host:port. It returns them normalized, without duplicates, in order.
func ParseList(text string) ([]string, error) {
	fields := strings.FieldsFunc(text, func(r rune) bool { return r == ',' || r == ';' || unicode.IsSpace(r) })
	var out []string
	var bad []string
	for _, f := range fields {
		n, err := Normalize(f)
		if err != nil {
			bad = append(bad, f)
			continue
		}
		if !slices.Contains(out, n) {
			out = append(out, n)
		}
	}
	if len(bad) > 0 {
		return nil, fmt.Errorf("not domains: %s", strings.Join(bad, ", "))
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no domains given")
	}
	return out, nil
}

// Covers reports whether entry e allows host h (both normalized; h without a leading dot).
func Covers(e, h string) bool { return presets.Covers(e, h) }

// ChromeHost is Claude in Chrome's relay to the user's browser. Only sessions that opt in reach
// it: through it the agent drives the user's signed-in Chrome, outside the allowlist.
const ChromeHost = "bridge.claudeusercontent.com"

// Sources are the inputs of one sandbox's allowlist.
type Sources struct {
	Presets []string // preset names (the always-on presets are added)
	Global  []string // config.yaml allow
	User    []string // allowlist.txt
	Project []string // project allow
	Chrome  bool     // allow ChromeHost (a session with Claude in Chrome)
}

// List returns the sandbox's allowlist: sorted, without duplicates or entries already covered
// by a broader one (Squid refuses overlapping dstdomain entries).
func List(src Sources) ([]string, error) {
	names := src.Presets
	if err := presets.Check(names); err != nil {
		return nil, err
	}
	var all []string
	for _, p := range presets.Catalogue() {
		if p.Always || slices.Contains(names, p.Name) { // always: the agent can't work without it
			all = append(all, p.Hosts...)
		}
	}
	for _, group := range [][]string{src.Global, src.User, src.Project} {
		for _, d := range group {
			n, err := Normalize(d)
			if err != nil {
				return nil, err
			}
			all = append(all, n)
		}
	}
	if src.Chrome {
		all = append(all, ChromeHost)
	}
	return Minimize(all), nil
}

// Group is one source of an allowlist's entries, as the app shows them.
type Group struct {
	Kind  string   `json:"kind"`  // preset, project, user (allowlist.txt), global (config.yaml), chrome
	Name  string   `json:"name"`  // the preset's name; empty for the other kinds
	Hosts []string `json:"hosts"` // as listed there
}

// Groups returns where an allowlist's entries come from, in the order List adds them. It checks
// the presets as List does.
func Groups(src Sources) ([]Group, error) {
	if err := presets.Check(src.Presets); err != nil {
		return nil, err
	}
	var out []Group
	for _, p := range presets.Catalogue() {
		if p.Always || slices.Contains(src.Presets, p.Name) {
			out = append(out, Group{Kind: "preset", Name: p.Name, Hosts: p.Hosts})
		}
	}
	for _, g := range []struct {
		kind  string
		hosts []string
	}{{"global", src.Global}, {"user", src.User}, {"project", src.Project}} {
		if len(g.hosts) > 0 {
			out = append(out, Group{Kind: g.kind, Hosts: g.hosts})
		}
	}
	if src.Chrome {
		out = append(out, Group{Kind: "chrome", Hosts: []string{ChromeHost}})
	}
	return out, nil
}

// Minimize sorts entries and drops those covered by another entry.
func Minimize(entries []string) []string {
	slices.Sort(entries)
	entries = slices.Compact(entries)
	var out []string
	for _, e := range entries {
		host := strings.TrimPrefix(e, ".")
		covered := false
		for _, o := range entries {
			if o != e && strings.HasPrefix(o, ".") && Covers(o, host) && (!strings.HasPrefix(e, ".") || len(o) < len(e)) {
				covered = true
				break
			}
		}
		if !covered {
			out = append(out, e)
		}
	}
	return out
}

// File renders an allowlist for Squid.
func File(entries []string) []byte {
	var b strings.Builder
	b.WriteString("# Generated by jailwick. Add domains with `jw allow <domain>`.\n")
	for _, e := range entries {
		b.WriteString(e + "\n")
	}
	return []byte(b.String())
}

// Denied is one host the proxy refused.
type Denied struct {
	Host     string
	Count    int
	First    time.Time
	Last     time.Time
	Projects []string
}

// verifyProbes are hosts jailwick's own verify checks expect to be refused.
var verifyProbes = []string{"example.com", "host.docker.internal", "169.254.169.254"}

// maxDenied bounds the hosts ParseDenied collects: the sandbox chooses which hosts it tries.
const maxDenied = 5000

// hostRE is what a host name or IP address can be; anything else in a log isn't one.
var hostRE = regexp.MustCompile(`^[a-z0-9]([a-z0-9._:-]*[a-z0-9])?$|^\[[0-9a-f:.]+\]$`)

// ParseDenied reads Squid access-log lines and adds denied requests to acc (by host). The hosts
// are what the sandbox asked for, so only real host names are kept, and at most maxDenied.
func ParseDenied(r io.Reader, project string, acc map[string]*Denied) {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 64*1024), 1024*1024)
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) < 7 || !strings.Contains(f[3], "DENIED") {
			continue
		}
		host := hostOf(f[6])
		if host == "" || slices.Contains(verifyProbes, host) {
			continue
		}
		ts, _ := strconv.ParseFloat(f[0], 64)
		when := time.Unix(int64(ts), 0)
		d := acc[host]
		if d == nil {
			if len(acc) >= maxDenied {
				continue
			}
			d = &Denied{Host: host}
			acc[host] = d
		}
		d.Count++
		if when.After(d.Last) {
			d.Last = when
		}
		if d.First.IsZero() || when.Before(d.First) {
			d.First = when
		}
		if !slices.Contains(d.Projects, project) {
			d.Projects = append(d.Projects, project)
		}
	}
}

func hostOf(target string) string {
	h := ""
	if strings.Contains(target, "://") {
		if u, err := url.Parse(target); err == nil {
			h = u.Hostname()
		}
	} else if end := strings.IndexByte(target, ']'); strings.HasPrefix(target, "[") && end > 0 {
		h = target[:end+1] // [IPv6]:port
	} else {
		h, _, _ = strings.Cut(target, ":")
	}
	if h = strings.ToLower(h); len(h) > 253 || !hostRE.MatchString(h) {
		return ""
	}
	return h
}

// MergeDenied adds one project's refusals (from ParseDenied) to those of others; from is left as
// it was.
func MergeDenied(into, from map[string]*Denied) {
	for h, d := range from {
		have := into[h]
		if have == nil {
			c := *d
			c.Projects = slices.Clone(d.Projects)
			into[h] = &c
			continue
		}
		have.Count += d.Count
		if d.Last.After(have.Last) {
			have.Last = d.Last
		}
		if !d.First.IsZero() && (have.First.IsZero() || d.First.Before(have.First)) {
			have.First = d.First
		}
		have.Projects = append(have.Projects, d.Projects...)
	}
}

// SortDenied orders by count, then most recent.
func SortDenied(acc map[string]*Denied) []Denied {
	out := make([]Denied, 0, len(acc))
	for _, d := range acc {
		out = append(out, *d)
	}
	slices.SortFunc(out, func(a, b Denied) int {
		if a.Count != b.Count {
			return b.Count - a.Count
		}
		return b.Last.Compare(a.Last)
	})
	return out
}
